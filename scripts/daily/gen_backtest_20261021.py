def stat(key, first_only=False):
    done = [x for x in rows if x.get('status') != 'no_result']
    if first_only:
        n = sum(1 for x in done if x[key] == 'first')
    else:
        n = sum(1 for x in done if x.get(key) in ('first', 'second', 'hit'))
    return n, len(done)


