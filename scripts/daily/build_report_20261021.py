def pct(x):
    return '%.1f%%' % (x * 100)


def top5(r):
    return ' > '.join('**%d-%d**(%s)' % (a, b, pct(p)) for a, b, p in r['top_scores'][:5])


def ht3(r):
    return ' > '.join('**%s**(%s)' % (k, pct(v)) for k, v in r['htft_top3'])


def hc_cn(d):
    return {'home': '胜', 'draw': '平', 'away': '负'}[d]


def ttg_row(r):
    n1, n2 = r['ttg_top2']
    p1 = r['tg'][str(n1)]
    p2 = r['tg'][str(n2)]
    tier = r['tier']
    if n1 == 1:
        tier = '闷战超小球(0-1球)'
    elif n1 == 2 and n2 == 1:
        tier = '小球(1-2球)'
    elif n1 == 2 and n2 == 3:
        tier = '常规正常球(2-3球)'
    side = '大' if n1 >= 3 else '小'
    return '**%s**（%s）：**%d球**(%s) / **%d球**(%s)' % (tier, side, n1, pct(p1), n2, pct(p2))


def score_note(r):
    return '；'.join('%d-%d(%s)' % (a, b, pct(p)) for a, b, p in r['band'][:3])


