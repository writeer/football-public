def rank_cn(s):
    if not s:
        return '—'
    s = str(s)
    for lg in ('澳超', '德乙', '法甲', '挪超', '荷乙', '德甲', '英冠', '西甲', '葡超', '巴甲'):
        if s.startswith(lg):
            return '%s第%s' % (lg, s[len(lg):])
    return s


def eu(v):
    if v >= 1e8:
        return '%.2f亿欧' % (v / 1e8)
    return '%.0f万欧' % (v / 1e4)


def odd(r, mkt, key):
    src = r.get('odds_' + mkt) or {}
    v = src.get(key)
    return float(v) if v else None


def prod(odds):
    vals = [o for o in odds if o]
    if len(vals) != len(odds):
        return None
    p = 1.0
    for v in vals:
        p *= v
    return p


def odds_cell(odds):
    return ' x '.join(('%.2f' % o) if o else '—' for o in odds)


def total_cell(odds):
    p = prod(odds)
    return ('%.2f' % p) if p else '—'


